/** Turns a catalogue run into a readable report. Usage: catalog-report <results.jsonl> <report.md>. Fails if the catalogue is not fully proven. */
import { readFileSync, writeFileSync } from 'node:fs';

interface Result {
    id: string;
    area: string;
    gesture: string;
    expected: string;
    status: 'proved' | 'limit' | 'trial';
    note?: string;
    passed: boolean;
}

const AREAS = ['Everyday gestures', 'Names', 'Photos and music', 'Notes', 'Machine life', 'Service failures', 'Drive view', 'Conflict matrix', 'Crash at every step'];

const [input, output] = process.argv.slice(2) as [string, string];
const rows: Result[] = readFileSync(input, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const problems: string[] = [];
const seen = new Set<string>();
for (const r of rows) {
    if (seen.has(r.id)) problems.push(`duplicate id: ${r.id}`);
    seen.add(r.id);
    if (!r.passed) problems.push(`failed: ${r.id}`);
}
for (const a of AREAS) if (!rows.some((r) => r.area === a)) problems.push(`no row in area: ${a}`);

const mark = (r: Result) => (!r.passed ? '❌' : r.status === 'limit' ? '⚠️ known limit' : r.status === 'trial' ? '🧪 to confirm in the trial' : '✅');
const cell = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
const count = (s: Result['status']) => rows.filter((r) => r.passed && r.status === s).length;
const lines = [
    '# Test catalogue',
    '',
    'Generated by `scripts/catalog-report.ts`: every line below is a test that ran. Do not edit by hand.',
    '',
    `${rows.length} rows: ${count('proved')} proved, ${count('limit')} known limits, ${count('trial')} to confirm in the real trial, ${rows.filter((r) => !r.passed).length} failed.`,
    '',
];
const gaps = rows.filter((r) => r.note?.startsWith('Policy gap'));
if (gaps.length) lines.push(`${gaps.length} conflict cells are not covered by docs/design.md: their current behaviour is tested, not yet agreed as policy.`, '');
for (const a of AREAS) {
    lines.push(`## ${a}`, '', '| | Situation | Expected | Note |', '|---|---|---|---|');
    for (const r of rows.filter((x) => x.area === a)) lines.push(`| ${mark(r)} | ${cell(r.gesture)} | ${cell(r.expected)} | ${cell(r.note ?? '')} |`);
    lines.push('');
}
writeFileSync(output, `${lines.join('\n')}\n`);
if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
}
console.log(`${rows.length} rows, all passed`);
